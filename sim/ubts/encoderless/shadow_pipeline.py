"""Sensor -> compact motion -> body-feedback diagnostic integration.

No ROS, actuator, wheel-state, oracle or captured-command input exists here.
An explicit SIM profile enables *conditional* shadow calculations under modeled
static/level/height-stable conditions. It is a caller assertion bound to frozen
evidence hashes, never physical-field proof or an execution authorization.
Clocks are sampled again after registration so its work cannot evade deadlines.
Every fault/STOP latches zero until an explicit, previously unused epoch reset.
"""
