MAX_IMU_WINDOW = 64
MAX_IMU_BRACKET_NS = 60_000_000
SIM_DOMAIN = 'isolated_generated_static_flat_instant'
LIVE_CLOCK_MAX_AGE_NS = 100_000_000


def _label(value):
    return isinstance(value, str) and bool(value.strip()) and len(value) <= 256


def _hash(value):
    return (isinstance(value, str) and len(value) == 64
            and all(c in '0123456789abcdef' for c in value))


@dataclass(frozen=True)
class ClockReading:
    source_ns: int
    receipt_ns: int

    def __post_init__(self):
        if not _stamp(self.source_ns) or not _stamp(self.receipt_ns):
            raise ValueError('invalid_clock')


@dataclass(frozen=True)
class LiveClockReading(ClockReading):
    """An actual /clock observation, sampled independently of scan processing.

    source_ns is the received /clock value, never a sensor-header watermark.
    receipt_ns is current monotonic time; clock_receipt_ns is the callback's
    actual monotonic receipt, and progress_receipt_ns last source-time advance.
    These are adapter-supplied provenance, not authenticated time attestations.
    """
    run_id: str
    clock_sequence: int
    clock_receipt_ns: int
    progress_receipt_ns: int

    def __post_init__(self):
        super().__post_init__()
        if (not _label(self.run_id) or not _stamp(self.clock_sequence) or self.clock_sequence == 0
                or not _stamp(self.clock_receipt_ns) or not _stamp(self.progress_receipt_ns)
                or not self.progress_receipt_ns <= self.clock_receipt_ns <= self.receipt_ns):
            raise ValueError('invalid_live_clock_provenance')


@dataclass(frozen=True)
class ReceivedScan:
    scan: CompactScan
    receipt_ns: int

    def __post_init__(self):
        if not isinstance(self.scan, CompactScan) or not _stamp(self.receipt_ns):
            raise ValueError('invalid_received_scan')


@dataclass(frozen=True)
class ImuSample:
    """Unmodified numeric fields and true receipt clock, not storage log time.

    Malformed/unavailable numeric groups remain representable and are rejected
    by the existing ROS IMU group contract when used. No -1 reinterpretation.
    """
    stamp_ns: int
    receipt_ns: int
    frame_id: str
    quaternion_xyzw: tuple
    angular_velocity: tuple
    orientation_covariance: tuple
    angular_velocity_covariance: tuple


@dataclass(frozen=True)
class SimOperatingProfile:
    """Conditional modeled domain, never an attestation generated by a fit.

    Caller must audit the referenced exact capture, CDR validation and fixture.
    The domain asserts instantaneous scans, static returns, a settled flat body,
    no height change, and a body-aligned IMU. Mount is known in the SIM model.
    A roll/pitch guard can reject this model; passing it cannot prove height or
    static support. active_from_ns explicitly excludes the declared settling
    period. Real recordings have no supported profile in this module.
    """
    profile_id: str
    capture_sha256: str
    cdr_validation_sha256: str
    fixture_sha256: str
    scan_frame: str
    imu_frame: str
    mount: LaserMount
    active_from_ns: int
    max_roll_pitch_rad: float
    operating_domain: str

    def __post_init__(self):
        if (not all(_label(v) for v in (self.profile_id, self.scan_frame, self.imu_frame))
                or not all(_hash(v) for v in (self.capture_sha256,
                                             self.cdr_validation_sha256, self.fixture_sha256))
                or not isinstance(self.mount, LaserMount)
                or not _stamp(self.active_from_ns)
                or not _number(self.max_roll_pitch_rad)
                or not 0 < self.max_roll_pitch_rad <= .05
                or self.operating_domain != SIM_DOMAIN):
            raise ValueError('invalid_conditional_sim_profile')


@dataclass(frozen=True)
class LiveSimOperatingProfile:
    """Explicit modeled live-SIM assumptions, with no frozen-capture fiction.

    fixture_sha256 pins SDF; source_contract_sha256 identifies a prior bounded
    native-CDR preflight of field/frame/covariance/instant-scan conventions.
    clock_provenance_sha256 identifies that run's independent /clock preflight.
    The caller validates these files and binds run_id before construction.
    A small preflight cannot prove whole-run static/level/height assumptions;
    they remain conditional properties of the independently audited fixture.
    """
    profile_id: str
    fixture_sha256: str
    source_contract_sha256: str
    clock_provenance_sha256: str
    run_id: str
    scan_frame: str
    imu_frame: str
    mount: LaserMount
    active_from_ns: int
    max_roll_pitch_rad: float
    operating_domain: str

    def __post_init__(self):
        if (not all(_label(v) for v in (self.profile_id,self.run_id,self.scan_frame,self.imu_frame))
                or not all(_hash(v) for v in (self.fixture_sha256,self.source_contract_sha256,
                                              self.clock_provenance_sha256))
                or not isinstance(self.mount,LaserMount) or not _stamp(self.active_from_ns)
                or not _number(self.max_roll_pitch_rad) or not 0 < self.max_roll_pitch_rad <= .05
                or self.operating_domain != SIM_DOMAIN):
            raise ValueError('invalid_conditional_live_sim_profile')

    @property
    def evidence_ref(self):
        # Compact's evidence label is bounded. Hash the complete declared live
        # profile rather than dropping run/mount/provenance fields from the ref.
        encoded=json.dumps(asdict(self),sort_keys=True,separators=(',',':'),allow_nan=False).encode()
        return 'modeled-live-profile:'+hashlib.sha256(encoded).hexdigest()


@dataclass(frozen=True)
class ImuPairing:
    reason: str
    start_indices: tuple = ()
    end_indices: tuple = ()
    yaw_delta_rad: float | None = None
    yaw_rate_rad_s: float | None = None
    rate_stamp_ns: int | None = None
    rate_receipt_ns: int | None = None
    covariance_unknown: bool | None = None


@dataclass(frozen=True)
class PipelineResult:
    reason: str
    epoch: str | None
    sequence: int | None
    command: object
    registration: object | None = None
    pairing: ImuPairing | None = None
    motion: object | None = None
    conditional_sim_profile: str | None = None
    execution_eligible: bool = field(default=False, init=False)
    runtime_authority: bool = field(default=False, init=False)


def _angles(quaternion):
    x, y, z, w = quaternion
    roll = math.atan2(2*(w*x+y*z), 1-2*(x*x+y*y))
    pitch = math.asin(max(-1., min(1., 2*(w*y-z*x))))
    yaw = math.atan2(2*(w*z+x*y), 1-2*(y*y+z*z))
    return roll, pitch, yaw


def pair_imu(samples, previous_stamp_ns, stamp_ns, *, frame_id, receipt_now_ns,
             max_roll_pitch_rad=None):
    """Bracket yaw with available IMUs; use the actual lower-end gyro sample.

    Only yaw is interpolated. Yaw rate, its source stamp and receipt are from
    one actual sample at/before the ending scan, never a synthesized timestamp.
    The caller must wait for bounded brackets before invoking, or accept STOP;
    unavailable future messages and extrapolation cannot supply evidence.
    """
    if (not isinstance(samples, tuple) or not 1 <= len(samples) <= MAX_IMU_WINDOW
            or not all(isinstance(s, ImuSample) for s in samples)
            or not _stamp(previous_stamp_ns) or not _stamp(stamp_ns)
            or not _stamp(receipt_now_ns) or not _label(frame_id)
            or (max_roll_pitch_rad is not None and (not _number(max_roll_pitch_rad)
                or not 0 < max_roll_pitch_rad <= .05))):
        return ImuPairing('invalid_imu_window')
    if any(not _stamp(s.stamp_ns) or not _stamp(s.receipt_ns) for s in samples):
        return ImuPairing('invalid_imu_timestamps')
    if any(a.stamp_ns >= b.stamp_ns or a.receipt_ns > b.receipt_ns
           for a, b in zip(samples, samples[1:])):
        return ImuPairing('reordered_imu_window')
    if any(s.frame_id != frame_id for s in samples):
        return ImuPairing('imu_frame_mismatch')
    if any(s.receipt_ns > receipt_now_ns for s in samples):
        return ImuPairing('imu_not_yet_received')
    stamps = [s.stamp_ns for s in samples]
    brackets, yaws, unknown = [], [], False
    for at in (previous_stamp_ns, stamp_ns):
        index = bisect_left(stamps, at)
        if index < len(stamps) and stamps[index] == at:
            lo = hi = index
        elif 0 < index < len(stamps):
            lo, hi = index-1, index
        else:
            return ImuPairing('imu_outside_retained_span')
        gap = stamps[hi]-stamps[lo]
        if gap > MAX_IMU_BRACKET_NS:
            return ImuPairing('imu_bracket_gap_exceeded')
        angles = []
        for i in (lo, hi):
            sample = samples[i]
            values = dict(quaternion=sample.quaternion_xyzw,
                          orientation_covariance=sample.orientation_covariance,
                          angular_velocity=sample.angular_velocity,
                          angular_velocity_covariance=sample.angular_velocity_covariance)
            orientation = _imu_group(values, 'quaternion', 'orientation_covariance', 4)
            angular = _imu_group(values, 'angular_velocity', 'angular_velocity_covariance', 3)
            for name, group in (('orientation', orientation), ('angular_velocity', angular)):
                if not group.valid or not group.available:
                    return ImuPairing('imu_'+name+'_'+group.reason)
                unknown = unknown or group.uncertainty_unknown
            roll, pitch, yaw = _angles(orientation.values)
            if max_roll_pitch_rad is not None and max(abs(roll), abs(pitch)) > max_roll_pitch_rad:
                return ImuPairing('outside_conditional_planar_profile')
            angles.append(yaw)
        fraction = 0. if lo == hi else (at-stamps[lo])/gap
        delta = math.atan2(math.sin(angles[1]-angles[0]), math.cos(angles[1]-angles[0]))
        yaws.append(angles[0]+fraction*delta)
        brackets.append((lo, hi))
    delta = math.atan2(math.sin(yaws[1]-yaws[0]), math.cos(yaws[1]-yaws[0]))
    rate = samples[brackets[1][0]]
    return ImuPairing('bracketed_available_imu', brackets[0], brackets[1], delta,
                      float(rate.angular_velocity[2]), rate.stamp_ns, rate.receipt_ns, unknown)


class ShadowPipeline:
    """One ordered scan pair per step; zero output after any STOP/fault.

    A rejected pair is still a result. Recovery is explicitly caller-owned:
    reset a new epoch and submit only the next adjacent pair with that epoch.
    reset() never carries integrators, velocities, PWM or inferred pose across
    the boundary. The first accepted pair in each epoch holds zero output.
    Desired velocities are targets only; feedback comes solely from sensors.
    """
    def __init__(self, mount, calibration, *, scan_frame, imu_frame, profile=None,
                 config=CompactConfig()):
        if (not isinstance(mount, LaserMount) or not isinstance(calibration, VelocityCalibration)
                or not _label(scan_frame) or not _label(imu_frame)
                or not isinstance(config, CompactConfig)):
            raise ValueError('explicit_shadow_configuration_required')
        if profile is not None and (not isinstance(profile, (SimOperatingProfile,LiveSimOperatingProfile))
                or (profile.mount, profile.scan_frame, profile.imu_frame) != (mount, scan_frame, imu_frame)):
            raise ValueError('sim_profile_configuration_mismatch')
        self.profile, self.config = profile, config
        self.scan_frame, self.imu_frame = scan_frame, imu_frame
        self.estimator, self.tracker = BodyMotionEstimator(mount), BodyVelocityTracker(calibration)
        self.epoch, self.fault = None, 'not_initialized'
        self.used_epochs = set()
        self.last_motion = None
        self.last_clock = None

    def reset(self, epoch):
        if not _epoch(epoch) or epoch in self.used_epochs or len(self.used_epochs) >= 10000:
            raise ValueError('new_bounded_epoch_required')
        self.estimator.reset(epoch)
        self.tracker.reset(epoch)
        self.epoch, self.fault, self.last_motion = epoch, None, None
        self.last_clock = None
        self.used_epochs.add(epoch)

    def stop(self, reason='operator_stop', *, sequence=None, registration=None,
             pairing=None, motion=None):
        command = self.tracker.stop(reason)
        self.fault = self.fault or command.reason
        return PipelineResult(self.fault, self.epoch, sequence, command, registration,
                              pairing, motion, self.profile.profile_id if self.profile else None)

    def watchdog(self, clock):
        if self.fault:
            return self.stop(self.fault)
        if not isinstance(clock, ClockReading):
            return self.stop('invalid_clock')
        live_error=self._live_clock_error(clock,self.last_clock)
        if live_error:
            return self.stop(live_error)
        if self.last_clock and (clock.source_ns < self.last_clock.source_ns
                                or clock.receipt_ns < self.last_clock.receipt_ns):
            return self.stop('clock_regression')
        error = motion_error(self.last_motion, epoch=self.epoch,
                             source_now_ns=clock.source_ns, receipt_now_ns=clock.receipt_ns)
        if error:
            return self.stop(error)
        self.last_clock = clock
        return None

    @staticmethod
    def _clock(clocks):
        try:
            value = clocks()
            return value if isinstance(value, ClockReading) else None
        except Exception:
            return None

    def _live_clock_error(self, clock, previous=None):
        if not isinstance(self.profile,LiveSimOperatingProfile):
            return None
        if not isinstance(clock,LiveClockReading) or clock.run_id != self.profile.run_id:
            return 'live_clock_provenance_mismatch'
        if clock.receipt_ns-clock.clock_receipt_ns > LIVE_CLOCK_MAX_AGE_NS:
            return 'live_clock_receipt_stale'
        if clock.receipt_ns-clock.progress_receipt_ns > LIVE_CLOCK_MAX_AGE_NS:
            return 'live_clock_source_stalled'
        if isinstance(previous,LiveClockReading):
            if (clock.clock_sequence < previous.clock_sequence
                    or clock.clock_receipt_ns < previous.clock_receipt_ns
                    or clock.progress_receipt_ns < previous.progress_receipt_ns):
                return 'live_clock_provenance_regression'
            if (clock.clock_sequence == previous.clock_sequence
                    and (clock.source_ns,clock.clock_receipt_ns,clock.progress_receipt_ns)
                    != (previous.source_ns,previous.clock_receipt_ns,previous.progress_receipt_ns)):
                return 'live_clock_reused_sequence_changed'
        return None

    def step(self, previous, current, imu_samples, desired_linear_m_s, desired_yaw_rad_s,
             *, sequence, clocks):
        if self.fault:
            return self.stop(self.fault, sequence=sequence)
        if not _stamp(sequence) or not callable(clocks):
            return self.stop('invalid_sequence_or_clock', sequence=sequence)
        if not all(_number(v) for v in (desired_linear_m_s, desired_yaw_rad_s)):
            return self.stop('invalid_desired_velocity', sequence=sequence)
        calibration = self.tracker.calibration
        if (abs(desired_linear_m_s) > calibration.max_desired_linear_m_s
                or abs(desired_yaw_rad_s) > calibration.max_desired_yaw_rad_s):
            return self.stop('invalid_desired_velocity', sequence=sequence)
        if desired_linear_m_s == 0. and desired_yaw_rad_s == 0.:
            return self.stop('zero_command', sequence=sequence)
        if not isinstance(previous, ReceivedScan) or not isinstance(current, ReceivedScan):
            return self.stop('invalid_received_scan', sequence=sequence)
        before, after = previous.scan, current.scan
        if before.epoch != self.epoch or after.epoch != self.epoch:
            return self.stop('epoch_mismatch', sequence=sequence)
        if before.frame_id != self.scan_frame or after.frame_id != self.scan_frame:
            return self.stop('scan_frame_mismatch', sequence=sequence)
        if current.receipt_ns < previous.receipt_ns:
            return self.stop('reordered_scan_receipt', sequence=sequence)
        start = self._clock(clocks)
        if not isinstance(start, ClockReading):
            return self.stop('invalid_clock', sequence=sequence)
        live_error=self._live_clock_error(start,self.last_clock)
        if live_error:
            return self.stop(live_error,sequence=sequence)
        if self.last_clock and (start.source_ns < self.last_clock.source_ns
                                or start.receipt_ns < self.last_clock.receipt_ns):
            return self.stop('clock_regression', sequence=sequence)
        if previous.receipt_ns > start.receipt_ns or current.receipt_ns > start.receipt_ns:
            return self.stop('scan_not_yet_received', sequence=sequence)
        profile = self.profile
        pairing = pair_imu(imu_samples, before.stamp_ns, after.stamp_ns,
                           frame_id=self.imu_frame, receipt_now_ns=start.receipt_ns,
                           max_roll_pitch_rad=profile.max_roll_pitch_rad if profile else None)
        if pairing.reason != 'bracketed_available_imu':
            return self.stop(pairing.reason, sequence=sequence, pairing=pairing)
        evidence = None
        if profile and before.stamp_ns >= profile.active_from_ns:
            reference = (profile.evidence_ref if isinstance(profile,LiveSimOperatingProfile)
                         else 'capture:'+profile.capture_sha256+'/cdr:'+profile.cdr_validation_sha256
                         +'/fixture:'+profile.fixture_sha256)
            evidence = ShadowEvidence(profile.profile_id, 'known_flat_fixture',
                reference,
                self.epoch, self.scan_frame, before.stamp_ns, after.stamp_ns,
                before.time_increment == 0. and after.time_increment == 0.,
                True, True, True, True, True)
        registration = propose_translation(before, after, pairing.yaw_delta_rad,
                                            config=self.config, evidence=evidence)
        finish = self._clock(clocks)
        live_error=self._live_clock_error(finish,start)
        if live_error:
            return self.stop(live_error,sequence=sequence,registration=registration,pairing=pairing)
        if (not isinstance(finish, ClockReading) or finish.source_ns < start.source_ns
                or finish.receipt_ns < start.receipt_ns):
            return self.stop('clock_regression_after_registration', sequence=sequence,
                             registration=registration, pairing=pairing)
        if not registration.shadow_eligible:
            return self.stop('registration_ineligible', sequence=sequence,
                             registration=registration, pairing=pairing)
        increment = ScanIncrement(self.epoch, sequence, before.stamp_ns, after.stamp_ns,
            current.receipt_ns, pairing.rate_stamp_ns, pairing.rate_receipt_ns,
            registration.proposed_delta_xy, pairing.yaw_delta_rad, pairing.yaw_rate_rad_s,
            registration.shadow_eligible, profile is not None)
        motion = self.estimator.observe(increment, source_now_ns=finish.source_ns,
                                        receipt_now_ns=finish.receipt_ns)
        if not motion.valid:
            return self.stop(motion.reason, sequence=sequence, registration=registration,
                             pairing=pairing, motion=motion)
        command = self.tracker.step(desired_linear_m_s, desired_yaw_rad_s, motion,
                                   source_now_ns=finish.source_ns, receipt_now_ns=finish.receipt_ns)
        if not command.valid:
            return self.stop(command.reason, sequence=sequence, registration=registration,
                             pairing=pairing, motion=motion)
        self.last_motion = motion
        self.last_clock = finish
        return PipelineResult(command.reason, self.epoch, sequence, command, registration,
                              pairing, motion, profile.profile_id)
